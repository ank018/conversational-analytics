REVENUE_SQL = """
SELECT sum(oi.price)
FROM order_items oi
JOIN orders o ON o.order_id = oi.order_id
WHERE o.order_status NOT IN ('canceled', 'unavailable')
"""

# label, sql, expected outcome: ok | a specific error_kind
CASES: list[tuple[str, str, str]] = [
    ("canonical revenue runs", REVENUE_SQL, "ok"),
    ("CTE allowed", "WITH t AS (SELECT 1 AS x) SELECT x FROM t", "ok"),
    ("FROM-first allowed", "FROM orders SELECT count(*)", "ok"),
    ("trailing semicolon fine", "SELECT 1;", "ok"),
    ("semicolon inside string", "SELECT 'a;b' AS s", "ok"),
    ("DROP inside comment", "SELECT 1 /* DROP TABLE orders */", "ok"),

    ("DROP blocked", "DROP TABLE orders", "blocked"),
    ("DELETE blocked", "DELETE FROM orders", "blocked"),
    ("COPY to file blocked", "COPY orders TO 'leak.csv'", "blocked"),
    ("ATTACH blocked", "ATTACH 'evil.db' AS evil", "blocked"),
    ("INSTALL blocked", "INSTALL httpfs", "blocked"),
    ("PRAGMA blocked", "PRAGMA database_list", "blocked"),
    ("stacked statements blocked", "SELECT 1; DROP TABLE orders", "blocked"),
    ("hidden second statement", "SELECT 1; -- harmless\nDELETE FROM orders",
     "blocked"),
    ("empty rejected", "   ", "blocked"),

    ("syntax error caught", "SELEC 1", "syntax"),
    ("unknown column caught", "SELECT nope FROM orders", "unknown_object"),
    ("unknown table caught", "SELECT * FROM no_such_table", "unknown_object"),

    ("row cap applies", "SELECT * FROM geolocation", "ok"),
    ("timeout fires",
     "SELECT count(*) FROM geolocation a, geolocation b, geolocation c",
     "timeout"),
]


def _self_test() -> int:
    con = connect()
    print("=" * 76)
    print("SANDBOX SELF-TEST")
    print("=" * 76)
    print(f"  db {DB_PATH}   row cap {MAX_ROWS:,}   timeout {TIMEOUT_S:g}s\n")

    failures = 0
    for label, sql, expect in CASES:
        res = run(sql, con=con)
        actual = "ok" if res.ok else res.error_kind
        passed = actual == expect
        failures += not passed
        mark = "PASS" if passed else "FAIL"
        detail = ""
        if res.ok and res.truncated:
            detail = f"capped at {res.row_count:,} rows"
        elif res.ok:
            detail = f"{res.row_count:,} rows, {res.elapsed_ms:.0f}ms"
        else:
            detail = (res.error or "")[:44]
        print(f"  {mark}  {label:<32} {actual:<15} {detail}")

    print()
    rev = run(REVENUE_SQL, con=con)
    value = rev.rows[0][0] if rev.ok and rev.rows else None
    expected = 13_494_400.74
    if value is not None and abs(value - expected) < 0.01:
        print(f"  PASS  revenue matches reference value {value:,.2f}")
    else:
        failures += 1
        print(f"  FAIL  revenue {value} != reference {expected:,.2f}")

    con.close()
    print()
    print("=" * 76)
    print(f"{len(CASES) + 1 - failures} of {len(CASES) + 1} passed")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(_self_test())
